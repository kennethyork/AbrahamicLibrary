"""A summary of Jubilees, for the pseudepigrapha division.

Jubilees belongs in this volume by every measure except one: no copy of it
could be found that separates the translation from the translator's own
commentary. Both public-domain editions of Charles run his notes down the
same column as the text, and an OCR of either produces pages where a
Victorian footnote and a second-century sentence look identical. Printing
that would break the rule the rest of this book keeps — that every departure
from the source is written down and can be checked.

So the book is described instead of printed, and the description says so
plainly at the top. It is written for this edition and quotes nothing.
"""

TITLE = 'The Book of Jubilees'
SUBTITLE = 'a summary — the text itself is not printed here'

NOTE = [
 'Why this is a summary. Jubilees is the one major work missing from this '
 'division, and its absence is deliberate rather than an oversight. The only '
 'public-domain translations of it — both by R. H. Charles, in 1902 and 1913 '
 '— print his commentary in the same column as the text, and no reliable mark '
 'separates the two. A reader could not tell an ancient sentence from a note '
 'about it. Everything else in this book can be checked against its source, '
 'and Jubilees could not be, so it is described here instead.',

 'What the book is. A retelling of Genesis, from the creation to the exodus '
 'from Egypt, presented as something dictated to Moses on Mount Sinai by an '
 'angel. It covers the same ground as Genesis and the first twelve chapters '
 'of Exodus, but it is not a commentary. It simply tells the story again, '
 'with additions, and expects to be believed.',

 'Where the name comes from. The book counts time in jubilees. A week is '
 'seven days, a week of years is seven years, and a jubilee is seven of those '
 '— forty-nine years. Every event is dated to the jubilee, the week and the '
 'year in which it happened, from the creation onward. Nothing else in '
 'ancient Jewish literature is dated so relentlessly, and the scheme is the '
 'reason the book exists: it is arguing that history runs on a fixed, '
 'countable pattern.',

 'The calendar. Underneath that is a quarrel about the calendar, and it is '
 'the sharpest thing in the book. Jubilees insists the year has three hundred '
 'and sixty-four days — exactly fifty-two weeks — so that every festival '
 'falls on the same weekday every year and none can ever fall on a sabbath. '
 'It calls anyone who keeps a lunar calendar mistaken and warns that they '
 'will get the holy days wrong. The Jerusalem temple used a lunar calendar. '
 'This was not an academic point.',

 'What it adds to Genesis. A great deal. Angels are created on the first day '
 'and keep the sabbath in heaven. The festivals are pushed back into the '
 'patriarchs’ lives, so that Noah keeps the Feast of Weeks and Abraham keeps '
 'Booths, centuries before Sinai. The patriarchs already keep the whole law, '
 'which has not yet been given. Abraham works out for himself that idols are '
 'nothing, burns down a temple of them, and gives up astrology. Adam and Eve '
 'are covered, at length and with feeling, because Jubilees hates nakedness — '
 'a live issue when Greek gymnasiums were being built in Jerusalem. And Levi '
 'is singled out and given the priesthood.',

 'The angels and the adversary. The watchers come down, take human wives and '
 'father giants, as in Enoch. When the demons are to be shut away, a figure '
 'called Mastema asks God to leave him a tenth of them to work with, and is '
 'allowed to. He is then behind everything that goes wrong: he prompts the '
 'testing of Abraham, and he is the one who tries to kill Moses on the road '
 'to Egypt. Jubilees is more willing than Genesis to name who is responsible '
 'for a disaster.',

 'What it is against. Marriage to foreigners, in the strongest terms in any '
 'Jewish writing of the period. Eating with gentiles. Nakedness. Getting the '
 'calendar wrong. Working on the sabbath, for which it prescribes death, and '
 'then lists what counts as work. The book was written somewhere around the '
 'middle of the second century before Christ, when Jewish practice was under '
 'real pressure to become Greek, and it reads like a man bolting the doors.',

 'How it survived, and why it matters. The Hebrew original was lost. A Greek '
 'version was lost. The book came down complete only in Ge’ez, the old '
 'language of Ethiopia, where the Ethiopian Orthodox Church still counts it '
 'as scripture. Then in the middle of the twentieth century fragments of the '
 'Hebrew turned up among the Dead Sea Scrolls — copies of Jubilees were more '
 'numerous there than copies of most books of the Bible, which tells you how '
 'seriously the community at Qumran took it.',

 'Where to read it. Charles’s translation is the standard English one and is '
 'in the public domain. It can be found in the second volume of his Apocrypha '
 'and Pseudepigrapha of the Old Testament, published at Oxford in 1913, and '
 'in his separate edition of 1902. If you have read the Book of Enoch earlier '
 'in this volume, you already know the world Jubilees is written in — the '
 'same watchers, the same calendar, the same conviction that the shape of '
 'history has been settled in advance and written down.',
]
