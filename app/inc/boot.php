<?php
/**
 * The Abrahamic Archive — configuration and the whole data layer.
 *
 * There is no framework and no dependency here. The reading texts are flat
 * JSON files under ../corpus, one per chapter, and the search index is a
 * SQLite database read through pdo_sqlite. Both sit outside the document
 * root, so nothing can be fetched except through these pages.
 */
declare(strict_types=1);

const APP_NAME    = 'The Abrahamic Archive';
const APP_TAGLINE = 'Judaism, Christianity and Islam in modern English';

/* The colours a reader can mark a verse with. Named rather than numbered so
   that a saved highlight survives a change to the palette, and so that the
   export a reader takes away says `amber` rather than `#f0c674`. */
/**
 * The reading plans, generated by `tools.build_plans` and checked against the
 * corpus when they are written, so a plan can never point at a chapter that
 * is not there.
 */
function plans(): array
{
    static $cache = null;
    if ($cache === null) {
        $raw = @file_get_contents(__DIR__ . '/../data/plans.json');
        $d = $raw ? json_decode($raw, true) : null;
        $cache = is_array($d) && isset($d['plans']) ? $d['plans'] : [];
    }
    return $cache;
}

/**
 * The verse for today. Chosen by the date rather than at random, so that
 * everyone who opens the archive on the same day meets the same verse and a
 * reload does not shuffle it.
 */
function verse_of_the_day(): ?array
{
    $raw = @file_get_contents(__DIR__ . '/../data/daily.json');
    $d = $raw ? json_decode($raw, true) : null;
    $all = is_array($d) && !empty($d['verses']) ? $d['verses'] : [];
    if (!$all) {
        return null;
    }
    $day = (int) floor(time() / 86400);
    return $all[$day % count($all)];
}

function plan(string $id): ?array
{
    foreach (plans() as $p) {
        if ($p['id'] === $id) {
            return $p;
        }
    }
    return null;
}

const HIGHLIGHTS = [
